const grid = document.querySelector("#productGrid");
const languageToggle = document.querySelector("#languageToggle");
let currentLanguage = "zh";

const renderShape = (shape) => `<span class="${shape}" aria-hidden="true"></span>`;

const renderProducts = () => {
  grid.innerHTML = products
    .map(
      (product) => `
        <article class="product-card">
          <div class="product-art" role="img" aria-label="${product.title[currentLanguage]} placeholder product image">
            <span class="badge">${product.badge[currentLanguage]}</span>
            ${product.shapes.map(renderShape).join("")}
          </div>
          <div class="product-info">
            <p class="eyebrow">${product.category[currentLanguage]}</p>
            <h3>${product.title[currentLanguage]}</h3>
            <div class="rating" aria-label="Five star rating">★★★★★ ${product.reviews[currentLanguage]}</div>
            <div class="price">${product.price}<del>${product.compareAt}</del></div>
          </div>
        </article>
      `,
    )
    .join("");
};

const applyLanguage = (language) => {
  currentLanguage = language;
  document.documentElement.lang = language === "zh" ? "zh-CN" : "en";
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    element.textContent = translations[language][key];
  });
  languageToggle.querySelector("strong").textContent = language === "zh" ? "EN" : "中文";
  languageToggle.setAttribute(
    "aria-label",
    language === "zh" ? "Switch to English" : "切换到中文",
  );
  renderProducts();
};

languageToggle.addEventListener("click", () => {
  applyLanguage(currentLanguage === "zh" ? "en" : "zh");
});

applyLanguage(currentLanguage);
